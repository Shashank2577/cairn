"""Voice the narration and retime the video around it.

    python narrate.py WORKDIR

1. Speaks each line of narration.js with the macOS `say` command (Samantha, 175 wpm) and measures
   every clip with ffprobe.
2. Retimes the captions: each line starts after the previous one ends, keeping the original gap
   (never less than 0.3 s), and its caption lasts at least as long as the original window or the
   voice, whichever is longer. Writes timing.js (new caption windows, the old→new time warp the
   page uses, the new duration) and WORKDIR/timing.json.
3. Synthesises the music on the new timing (music.py), places the voice, ducks the music under it
   (music sits 16 dB under the voice between lines and 22 dB under it while the voice speaks) and
   normalises the mix to -16 LUFS with ffmpeg's loudnorm in two passes. Result: WORKDIR/mix.wav.
Needs numpy, macOS `say` and ffmpeg/ffprobe.
"""
import json
import re
import subprocess
import sys
import wave
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
WORK = Path(sys.argv[1]).resolve()
WORK.mkdir(parents=True, exist_ok=True)
SR = 44100
VOICE, RATE = "Samantha", "175"
OLD_DUR = 112.0
MIN_GAP = 0.3


def js_array(path, name):
    src = (HERE / path).read_text()
    body = re.search(rf"window\.{name}\s*=\s*(\[.*?\n\]);", src, re.S).group(1)
    body = re.sub(r",\s*\]", "]", body)
    return json.loads(body)


def run(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True)


def read_wav(path):
    with wave.open(str(path)) as w:
        x = np.frombuffer(w.readframes(w.getnframes()), "<i2").astype(np.float64) / 32768
        return x.reshape(-1, w.getnchannels())


def write_wav(path, x):
    pcm = (np.clip(x, -1, 1) * 32767).astype("<i2")
    with wave.open(str(path), "wb") as w:
        w.setnchannels(x.shape[1]); w.setsampwidth(2); w.setframerate(SR); w.writeframes(pcm.tobytes())


def lufs(path):
    out = run("ffmpeg", "-hide_banner", "-nostats", "-i", str(path), "-af", "ebur128", "-f", "null", "-").stderr
    return float(re.findall(r"I:\s+(-?[\d.]+) LUFS", out)[-1])


captions = js_array("captions.js", "CAPTIONS")
lines = js_array("narration.js", "NARRATION")
assert len(captions) == len(lines), "one narration line per caption"

# 1. voice each line
clips = []
for i, text in enumerate(lines):
    aiff, wav = WORK / f"vo{i:02d}.aiff", WORK / f"vo{i:02d}.wav"
    run("say", "-v", VOICE, "-r", RATE, "-o", str(aiff), text)
    run("ffmpeg", "-y", "-v", "error", "-i", str(aiff), "-ar", str(SR), "-ac", "1", str(wav))
    d = float(run("ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(wav)).stdout)
    clips.append((wav, d))

# 2. retime
new, warp = [], [[0.0, 0.0]]
prev_old_end = prev_new_end = None
for (a, b, text), (_, d) in zip(captions, clips):
    if prev_new_end is None:
        A = a
    else:
        A = prev_new_end + max(MIN_GAP, a - prev_old_end)
    B = A + max(b - a, d + 0.25)
    new.append([round(A, 3), round(B, 3), text, round(d, 3)])
    warp += [[a, round(A, 3)], [b, round(B, 3)]]
    prev_old_end, prev_new_end = b, B
duration = round(prev_new_end + 2.5, 3)               # hold the end card after the last line
warp.append([OLD_DUR, duration])
assert duration < 130, duration

(HERE / "timing.js").write_text(
    "// Generated by narrate.py from captions.js, narration.js and the measured voice clips; do not edit.\n"
    "// VO: [start, end, caption, voice seconds] on the narrated timeline. WARP: [old, new] anchors that map\n"
    "// the narrated time back to the original 112 s timeline the scenes are written on.\n"
    f"window.VO = {json.dumps(new)};\nwindow.WARP = {json.dumps(warp)};\nwindow.DURATION = {duration};\n")
(WORK / "timing.json").write_text(json.dumps({"duration": duration, "warp": warp, "vo": new}))

# 3. music, voice, duck, mix
run(sys.executable, str(HERE / "music.py"), str(WORK / "music.wav"), str(WORK / "timing.json"))
music = read_wav(WORK / "music.wav")
n = int(duration * SR)
music = np.pad(music, ((0, max(0, n - len(music))), (0, 0)))[:n]
voice = np.zeros(n)
active = np.zeros(n)
for (wav, d), (A, B, _, _) in zip(clips, new):
    x = read_wav(wav)[:, 0]
    i = int((A + 0.05) * SR)
    x = x[: n - i]
    voice[i : i + len(x)] += x
    active[max(0, i - int(.15 * SR)) : min(n, i + len(x) + int(.25 * SR))] = 1
write_wav(WORK / "voice.wav", np.stack([voice, voice], 1))
write_wav(WORK / "music_n.wav", music)
lv, lm = lufs(WORK / "voice.wav"), lufs(WORK / "music_n.wav")
gain = 10 ** ((lv - 16 - lm) / 20)                      # music 16 dB under the voice between lines
k = int(0.25 * SR)                                       # 250 ms ramps
smooth = np.convolve(active, np.ones(k) / k, mode="same")
duck = 10 ** (-6 * smooth / 20)                          # a further 6 dB while speaking: 22 dB under
mix = music * (gain * duck)[:, None] + np.stack([voice, voice], 1)
write_wav(WORK / "premix.wav", mix * 0.5)

p1 = run("ffmpeg", "-hide_banner", "-nostats", "-i", str(WORK / "premix.wav"), "-af",
         "loudnorm=I=-16:TP=-1.5:LRA=11:print_format=json", "-f", "null", "-").stderr
m = json.loads(p1[p1.rindex("{"):p1.rindex("}") + 1])
run("ffmpeg", "-y", "-v", "error", "-i", str(WORK / "premix.wav"), "-af",
    f"loudnorm=I=-16:TP=-1.5:LRA=11:measured_I={m['input_i']}:measured_TP={m['input_tp']}:"
    f"measured_LRA={m['input_lra']}:measured_thresh={m['input_thresh']}:offset={m['target_offset']}:linear=true",
    "-ar", str(SR), str(WORK / "mix.wav"))
print(json.dumps({"duration": duration, "voice_lufs": lv, "music_lufs_raw": lm,
                  "music_gain_db": round(20 * np.log10(gain), 1), "mix_lufs": lufs(WORK / "mix.wav"),
                  "lines": [[l[0], l[1], l[3]] for l in new]}, indent=1))
