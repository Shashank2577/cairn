            f"| Nodes | {MAX_ELEMENTS:,} | `MermaidError` |",
            f"| Arrows | {MAX_RELATIONSHIPS:,} | `MermaidError` |",
            f"| Warnings | {mermaid_in.MAX_WARNINGS} | the rest are counted, not listed |",
            "| Binary data | any NUL byte | `MermaidError` |",
