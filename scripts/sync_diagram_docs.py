def render_taazaa(tokens: dict) -> str:
    """The Taazaa mapping with its counts measured, not asserted. Every number here comes from running the
    checker over the transcription, so the published claim and the code cannot drift apart."""
    from cairn.system.diagram import check as ck
    from cairn.system.diagram import schema

    out = [BEGIN, "",
           "# The Taazaa templates, and what replaces them", "",
           "The Taazaa documentation skill's Mermaid diagrams share five defects: one layered shape forced",
           "on every system, unlabelled arrows, levels mixed in one picture, no boundary, legend or element",
           "types, and nothing tying a box to code. Cairn does not edit that repository; it owns its own",
           "standard (`docs/diagram-standard/`) and the Taazaa diagrams were transcribed into the",
           "description format only so the defects could be counted.", "",
           "The transcriptions are in [`taazaa-original/`](taazaa-original/). Running the checker over them",
           "gives the numbers below, and every replacement in `examples/` passes with none.", "",
           "## The transcriptions, measured", "",
           "| Transcription | Violations | Rules it breaks |", "|---|---|---|"]
    for path in sorted(TAAZAA.glob("*.yaml")):
        d = schema.load_file(path)
        v = ck.check(d)
        out.append(f"| [`{path.name}`](taazaa-original/{path.name}) | {len(v)} | "
                   f"{', '.join(sorted(ck.rule_ids(v), key=lambda r: int(r[1:])))} |")
    out += ["", "## The five defects", ""]
    for defect, where in TAAZAA_DEFECTS:
        out += [f"**{defect}.** {where}", ""]
    out += ["## Which template becomes which replacement", "",
            "| Taazaa template diagram | Replacement | Why it changes |", "|---|---|---|"]
    for template, replacement, why in TAAZAA_MAP:
        if replacement.startswith("examples/"):
            stem = Path(replacement).name
            link = f"[{replacement}](examples/{stem}.svg)"
        else:
            link = replacement
        out.append(f"| {template} | {link} | {why} |")
    out += ["", "Examples 01 to 05, 07 and 08 describe a four-repository sandbox product (\"Shop\") used to",
            "test the system model; 06 and 09 describe Cairn's own code. Each `.md` beside an `.svg` in",
            "`examples/` is that diagram's evidence table.", ""]
    return "\n".join(out)


def render() -> dict[Path, str]:
    tokens = json.loads(CANON_TOKENS.read_text(encoding="utf-8"))
    return {RULES_MD: render_rules(tokens), MERMAID_MD: render_mermaid(tokens), TAAZAA_MD: render_taazaa(tokens)}


def main(check: bool = False) -> int:
    stale = []
    for path, text in render().items():
        try:
            current = path.read_text(encoding="utf-8")
        except FileNotFoundError:
            current = None
        if current != text:
            stale.append(path)
            if not check:
                path.write_text(text, encoding="utf-8", newline="\n")
    if check and stale:
        print("out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv))